drop policy if exists "Profiles can read self and admins can read all" on public.profiles;
create policy "Profiles can read self and admins can read all" on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "Projects are public" on public.projects;
create policy "Projects are public" on public.projects for select using (true);
drop policy if exists "Admins create projects" on public.projects;
create policy "Admins create projects" on public.projects for insert with check (public.is_admin());
drop policy if exists "Admins update projects" on public.projects;
create policy "Admins update projects" on public.projects for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins delete projects" on public.projects;
create policy "Admins delete projects" on public.projects for delete using (public.is_admin());

drop policy if exists "Anyone sends contact messages" on public.contact_messages;
create policy "Anyone sends contact messages" on public.contact_messages for insert to anon, authenticated with check (true);
drop policy if exists "Admins read messages" on public.contact_messages;
create policy "Admins read messages" on public.contact_messages for select using (public.is_admin());
drop policy if exists "Admins update messages" on public.contact_messages;
create policy "Admins update messages" on public.contact_messages for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins delete messages" on public.contact_messages;
create policy "Admins delete messages" on public.contact_messages for delete using (public.is_admin());

revoke update on public.profiles from anon, authenticated;
