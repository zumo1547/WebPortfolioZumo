create or replace function public.admin_delete_project(target_project_id bigint)
returns text[]
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  project_images jsonb;
  storage_paths text[];
begin
  if not public.is_admin() then
    raise exception 'Admin permission required' using errcode = '42501';
  end if;

  delete from public.projects where id = target_project_id returning images into project_images;
  if project_images is null then
    raise exception 'Project not found' using errcode = 'P0002';
  end if;

  select coalesce(array_agg(value), array[]::text[])
  into storage_paths
  from jsonb_array_elements_text(project_images) as value;
  return storage_paths;
end;
$$;

create or replace function public.admin_set_user_role(target_user_id uuid, next_role text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_admin() then
    raise exception 'Admin permission required' using errcode = '42501';
  end if;
  if next_role not in ('user', 'admin') then
    raise exception 'Invalid role' using errcode = '22023';
  end if;
  if target_user_id = auth.uid() then
    raise exception 'You cannot change your own role' using errcode = '42501';
  end if;
  if next_role = 'user'
     and (select role from public.profiles where id = target_user_id) = 'admin'
     and (select count(*) from public.profiles where role = 'admin') <= 1 then
    raise exception 'At least one admin is required' using errcode = '23514';
  end if;

  update public.profiles set role = next_role where id = target_user_id;
  if not found then
    raise exception 'User profile not found' using errcode = 'P0002';
  end if;
end;
$$;

